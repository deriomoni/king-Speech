export default function LevelIcon({
  levelId,
  color,
  hole,
}: {
  levelId: string;
  color: string;
  hole: string;
}) {
  const kind = levelIconKind(levelId);
  if (!kind) return <View style={{ width: LEVEL_ICON_BOX, height: LEVEL_ICON_BOX }} />;
  const [w, h] = SIZE[kind];
  const s = LEVEL_ICON_BOX / Math.max(w, h);
  return (
    <View
      style={{
        width: LEVEL_ICON_BOX,
        height: LEVEL_ICON_BOX,
        alignItems: "center",
        justifyContent: "center",
      }}
    >
      <Svg width={w * s} height={h * s} viewBox={`0 0 ${w} ${h}`}>
        <Glyph kind={kind} color={color} hole={hole} />
      </Svg>
    </View>
  );
}
