// Builds the "Get Ready" wordmark path from Pacifico (the Show Time logo's
// look-alike) into components/cheatsheet/getReadyWordmark.ts.
//
// Pacifico is heavier than the Show Time lettering, so the outline is thinned:
// glyph contours are flattened to polygons, merged into one shape (Pacifico's
// letters overlap at the joins) and offset inward by THIN on each side.
//
// usage: node scripts/get-ready-wordmark.js <dir-with-node_modules>
//   needs opentype.js and clipper-lib there (not app dependencies — install
//   them anywhere temporarily: npm i opentype.js@1.3.4 clipper-lib@6.4.2)
const fs = require("fs");
const path = require("path");
const mods = process.argv[2] ? path.join(process.argv[2], "node_modules") : "";
const opentype = require(path.join(mods, "opentype.js"));
const ClipperLib = require(path.join(mods, "clipper-lib"));

const ROOT = path.resolve(__dirname, "..");
const FONT = path.join(ROOT, "node_modules/@expo-google-fonts/pacifico/400Regular/Pacifico_400Regular.ttf");
const SIZE = 100;
const THIN = 1.55; // units eaten from each side of a stroke (font size 100)
const SCALE = 1000; // clipper works in integers
const STEP = 0.6; // curve flattening step, units

const font = opentype.loadSync(FONT);
const glyphPath = font.getPath("Get Ready", 0, SIZE, SIZE, { kerning: true });

// flatten to polygons
const polys = [];
let cur = null, px = 0, py = 0;
const add = (x, y) => { cur.push({ X: Math.round(x * SCALE), Y: Math.round(y * SCALE) }); px = x; py = y; };
for (const c of glyphPath.commands) {
  if (c.type === "M") { cur = []; polys.push(cur); add(c.x, c.y); }
  else if (c.type === "L") add(c.x, c.y);
  else if (c.type === "Q" || c.type === "C") {
    const x0 = px, y0 = py;
    const n = Math.max(2, Math.ceil(Math.hypot(c.x - x0, c.y - y0) / STEP));
    for (let i = 1; i <= n; i++) {
      const t = i / n, u = 1 - t;
      if (c.type === "Q") add(u * u * x0 + 2 * u * t * c.x1 + t * t * c.x, u * u * y0 + 2 * u * t * c.y1 + t * t * c.y);
      else add(u * u * u * x0 + 3 * u * u * t * c.x1 + 3 * u * t * t * c.x2 + t * t * t * c.x,
               u * u * u * y0 + 3 * u * u * t * c.y1 + 3 * u * t * t * c.y2 + t * t * t * c.y);
    }
  }
}

// union (nonzero) then inward offset
const merged = new ClipperLib.Paths();
const cl = new ClipperLib.Clipper();
cl.AddPaths(polys, ClipperLib.PolyType.ptSubject, true);
cl.Execute(ClipperLib.ClipType.ctUnion, merged, ClipperLib.PolyFillType.pftNonZero, ClipperLib.PolyFillType.pftNonZero);
const co = new ClipperLib.ClipperOffset(2, 0.05 * SCALE);
co.AddPaths(merged, ClipperLib.JoinType.jtRound, ClipperLib.EndType.etClosedPolygon);
let thin = new ClipperLib.Paths();
co.Execute(thin, -THIN * SCALE);
thin = ClipperLib.Clipper.CleanPolygons(thin, 0.03 * SCALE);

// bounds + path data
let x1 = Infinity, y1 = Infinity, x2 = -Infinity, y2 = -Infinity;
for (const p of thin) for (const { X, Y } of p) {
  x1 = Math.min(x1, X); y1 = Math.min(y1, Y); x2 = Math.max(x2, X); y2 = Math.max(y2, Y);
}
const pad = 1;
const ox = x1 / SCALE - pad, oy = y1 / SCALE - pad;
const w = (x2 - x1) / SCALE + pad * 2, h = (y2 - y1) / SCALE + pad * 2;
const f = (v) => (+v.toFixed(1)).toString();
const d = thin
  .map((p) => "M" + p.map(({ X, Y }) => `${f(X / SCALE - ox)} ${f(Y / SCALE - oy)}`).join("L") + "Z")
  .join("");

const out = `// Generated by scripts/get-ready-wordmark.js — "Get Ready" in Pacifico,
// thinned to the Show Time logo's stroke weight. Fill with nonzero.
export const GET_READY_W = ${w.toFixed(1)};
export const GET_READY_H = ${h.toFixed(1)};
export const GET_READY_D = ${JSON.stringify(d)};
`;
fs.writeFileSync(path.join(ROOT, "components/cheatsheet/getReadyWordmark.ts"), out);
console.log(`viewBox 0 0 ${w.toFixed(1)} ${h.toFixed(1)}, ${thin.length} contours, ${(d.length / 1024).toFixed(1)} KB`);
