/**
 * Russian feedback templates (spec §8.4).
 *
 * ≥4 phrasing variants per insight and per metric bucket so the selector can
 * avoid repeating the last two (§8.4.2). Placeholders: {word} {count}
 * {location} {cluster} {syllables} {synonyms} {N}. Tone: a fact without a
 * verdict on the person.
 */

import { InsightEvidence, InsightId } from './insights';

export type MetricKey =
  | 'clarity'
  | 'tempo'
  | 'punct'
  | 'loudness'
  | 'breath'
  | 'fillers'
  | 'tautology'
  | 'diversity'
  | 'pauseDiscipline';

export interface GrowthTemplate {
  variants: string[];
  action: string;
}

/** Fill placeholders from evidence + optional extras. */
export function fillTemplate(
  template: string,
  evidence: InsightEvidence,
  extras: Record<string, string> = {},
): string {
  const map: Record<string, string> = {
    word: evidence.word ?? '',
    count: evidence.count != null ? String(evidence.count) : '',
    location: evidence.location ?? '',
    cluster: evidence.cluster ?? '',
    syllables: evidence.syllables ?? '',
    N: evidence.count != null ? String(evidence.count) : '',
    ...extras,
  };
  return template.replace(/\{(\w+)\}/g, (_, k: string) => map[k] ?? '');
}

